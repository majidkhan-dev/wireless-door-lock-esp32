#define I2C_TIMEOUT    1000
#define COLUMN_OFFSET  2
#define I2C_MASTER_NUM I2C_NUM_0

static void ssd1306_send_cmd(uint8_t cmd)
{
    uint8_t data[2] = {0x00, cmd};
    i2c_master_write_to_device(I2C_MASTER_NUM, OLED_ADDR, data, 2,
                               I2C_TIMEOUT / portTICK_PERIOD_MS);
}

static void ssd1306_send_data(uint8_t *data, size_t len)
{
    uint8_t *buf = malloc(len + 1);
    if (!buf) return;
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    i2c_master_write_to_device(I2C_MASTER_NUM, OLED_ADDR, buf, len + 1,
                               I2C_TIMEOUT / portTICK_PERIOD_MS);
    free(buf);
}

void ssd1306_init(void)
{
    const uint8_t cmds[] = {
        0xAE, 0x20,0x00, 0xB0, 0xC8, 0x00, 0x10, 0x40,
        0x81,0x7F, 0xA1, 0xA6, 0xA8,0x3F, 0xA4, 0xD3,0x00,
        0xD5,0xF0, 0xD9,0x22, 0xDA,0x12, 0xDB,0x20, 0x8D,0x14, 0xAF
    };
    for (int i = 0; i < (int)sizeof(cmds); i++)
        ssd1306_send_cmd(cmds[i]);
}

void ssd1306_clear(void)
{
    uint8_t zeros[SSD1306_WIDTH];
    memset(zeros, 0, sizeof(zeros));
    for (int page = 0; page < SSD1306_PAGES; page++) {
        ssd1306_send_cmd(0xB0 + page);
        ssd1306_send_cmd(0x00 + COLUMN_OFFSET);
        ssd1306_send_cmd(0x10);
        ssd1306_send_data(zeros, SSD1306_WIDTH);
    }
}

void ssd1306_draw_text(uint8_t row, uint8_t col, const char *text)
{
    while (*text) {
        char c = *text++;
        if (c < 32 || c > 127) c = '?';
        uint8_t column = col + COLUMN_OFFSET;
        ssd1306_send_cmd(0xB0 + row);
        ssd1306_send_cmd(0x00 + (column & 0x0F));
        ssd1306_send_cmd(0x10 + (column >> 4));
        ssd1306_send_data((uint8_t *)font8x8_basic[c - 32], 8);
        col += 8;
    }
}
